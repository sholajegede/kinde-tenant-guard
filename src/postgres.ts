import type { VerifyCheck, VerifyResult } from "./guard.js";

/** The PostgreSQL setting that holds the active tenant for the current transaction. */
export const TENANT_SETTING = "app.tenant_id";
/** The PostgreSQL setting withSystem() turns on to reach every tenant. */
export const SYSTEM_SETTING = "app.tenant_guard_system";
/** The name of the policy the generated SQL creates on each table. */
export const POLICY_NAME = "tenant_guard_isolation";

/** A tenant table, described the same way for every adapter. */
export interface PostgresTenantTable {
  resource: string;
  schema: string;
  name: string;
  /** The tenant column's database name. */
  column: string;
  /** The column's SQL type, such as text or uuid. */
  type: string;
}

const ident = (value: string) => `"${value.replace(/"/g, '""')}"`;
export const qualified = (t: Pick<PostgresTenantTable, "schema" | "name">) => `${ident(t.schema)}.${ident(t.name)}`;
export const currentTenant = (cast: string) => `NULLIF(current_setting('${TENANT_SETTING}', true), '')::${cast}`;

/** The SQL that enables, forces and adds the tenant policy on each table, and stamps new rows with the tenant. */
export function rlsSql(tables: PostgresTenantTable[]): string {
  const parts = ["-- Generated by kinde-tenant-guard. Each tenant table only shows and accepts rows for the tenant in app.tenant_id."];
  for (const table of tables) {
    const name = qualified(table);
    const column = ident(table.column);
    const rule = `${column} = ${currentTenant(table.type)} OR current_setting('${SYSTEM_SETTING}', true) = 'on'`;
    parts.push(
      [
        `-- ${table.resource}`,
        `ALTER TABLE ${name} ENABLE ROW LEVEL SECURITY;`,
        `ALTER TABLE ${name} FORCE ROW LEVEL SECURITY;`,
        `DROP POLICY IF EXISTS ${POLICY_NAME} ON ${name};`,
        `CREATE POLICY ${POLICY_NAME} ON ${name} FOR ALL USING (${rule}) WITH CHECK (${rule});`,
        `ALTER TABLE ${name} ALTER COLUMN ${column} SET DEFAULT ${currentTenant(table.type)};`,
      ].join("\n"),
    );
  }
  return `${parts.join("\n\n")}\n`;
}

/** Runs one parameterized query and returns its rows. Each adapter supplies its own. */
export type PostgresQuery = (text: string, params: unknown[]) => Promise<Record<string, unknown>[]>;

/** Checks that the connection's role cannot skip row-level security, and that every table enforces the tenant policy. */
export async function verifyPostgres(query: PostgresQuery, tables: PostgresTenantTable[]): Promise<VerifyResult> {
  const checks: VerifyCheck[] = [];
  const [role] = await query("select current_user as name, r.rolsuper as super, r.rolbypassrls as bypass from pg_roles r where r.rolname = current_user", []);
  const bypasses = Boolean(role?.super) || Boolean(role?.bypass);
  checks.push({
    name: "database role",
    ok: !bypasses,
    detail: bypasses
      ? `The app connects as "${String(role?.name)}", which ${role?.super ? "is a superuser" : "has BYPASSRLS"}, so PostgreSQL skips row-level security on every query.`
      : `The app connects as "${String(role?.name)}", which row-level security applies to.`,
    ...(bypasses
      ? { fix: "Connect as a role without SUPERUSER or BYPASSRLS, for example: CREATE ROLE app_user LOGIN PASSWORD '...'; GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO app_user;" }
      : {}),
  });
  for (const table of tables) {
    const [state] = await query("select c.relrowsecurity as enabled, c.relforcerowsecurity as forced from pg_class c where c.oid = to_regclass($1)", [qualified(table)]);
    const [policy] = await query("select count(*)::int as count from pg_policies where schemaname = $1 and tablename = $2 and policyname = $3", [table.schema, table.name, POLICY_NAME]);
    const ok = Boolean(state?.enabled) && Boolean(state?.forced) && Number(policy?.count) > 0;
    checks.push({
      name: `${table.resource} (${table.schema}.${table.name})`,
      ok,
      detail: !state
        ? "The table does not exist."
        : ok
          ? "Row-level security is enabled and forced, with the tenant policy."
          : `Row-level security is ${state.enabled ? "enabled" : "not enabled"}, ${state.forced ? "forced" : "not forced"}, and the ${POLICY_NAME} policy is ${Number(policy?.count) > 0 ? "present" : "missing"}.`,
      ...(ok ? {} : { fix: "Run the SQL from adapter.migrationSql() in a migration." }),
    });
  }
  return { ok: checks.every((c) => c.ok), checks };
}
